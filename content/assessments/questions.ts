/**
 * Assessment bank. Every question cites the handbook section that supports the answer.
 * Numeric questions carry the expected answer in the stated display unit; the unit
 * test suite recomputes each one with lib/physics so the bank cannot drift from the
 * calculators. These are learning assessments, not professional certification.
 */
export type Level = "L1" | "L2" | "L3" | "L4" | "L5" | "L6";

interface Base {
  id: string;
  level: Level;
  section: string;
  prompt: string;
  explanation: string;
  hint?: string;
}
export interface McqQuestion extends Base {
  type: "mcq";
  choices: string[];
  answer: number;
}
export interface NumericQuestion extends Base {
  type: "numeric";
  answer: number;
  unit: string;
  /** relative tolerance, e.g. 0.02 = ±2% */
  tolerance: number;
}
export interface MatchQuestion extends Base {
  type: "match";
  pairs: Array<[string, string]>;
}
export type Question = McqQuestion | NumericQuestion | MatchQuestion;

